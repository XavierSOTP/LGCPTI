using LGC.PTI.Domain.Common;
using LGC.PTI.HTTPClient.Refit.Common;
using SoftSolute.Net.Refit;

namespace LGC.PTI.HTTPClient;

/// <summary>
/// Defines a PTI-specific dynamic URL manager used to resolve request destinations at runtime.
/// </summary>
public interface IPTIDynamicUrlManager : IRefitDynamicUrlManager
{
}

/// <summary>
/// Provides dynamic URL resolution for PTI HTTP requests.
/// </summary>
/// <remarks>
/// The manager obtains the current PTI base URL from <see cref="IPTISharableDataProvider"/>
/// and combines it with the relative request path produced by the configured Refit client.
/// </remarks>
public sealed class PTIDynamicUrlManager : BaseDynamicUrlManager<IPTISharableDataProvider>, IPTIDynamicUrlManager
{
    /// <summary>
    /// Initializes a new instance of the <see cref="PTIDynamicUrlManager"/> class.
    /// </summary>
    /// <param name="dynamicUrlProvider">
    /// The provider that supplies the current PTI base URL.
    /// </param>
    public PTIDynamicUrlManager(IPTISharableDataProvider dynamicUrlProvider) : base(dynamicUrlProvider)
    {
    }
}

/// <summary>
/// Provides a base implementation for resolving dynamic URLs for Refit HTTP clients.
/// </summary>
/// <typeparam name="TDynamicUrlProvider">
/// The type of dynamic URL provider used to obtain the current base URL.
/// </typeparam>
public abstract class BaseDynamicUrlManager<TDynamicUrlProvider> : IRefitDynamicUrlManager where TDynamicUrlProvider : IDynamicUrlProvider
{
    /// <summary>
    /// Defines the placeholder base address used when configuring the Refit HTTP client.
    /// </summary>
    private const string DUMMY_BASE_ADDRESS = "http://dummy.com";

    /// <summary>
    /// Defines the forward-slash character used when combining URL segments.
    /// </summary>
    private const char ForwardSlash = '/';

    /// <summary>
    /// Gets the placeholder base address used by the Refit HTTP client before
    /// the runtime URL is resolved.
    /// </summary>
    public Uri DefaultBaseAddress => new Uri("http://dummy.com");

    /// <summary>
    /// Gets the provider that supplies the current dynamic base URL.
    /// </summary>
    private IDynamicUrlProvider DynamicUrlProvider { get; }

    /// <summary>
    /// Initializes a new instance of the <see cref="BaseDynamicUrlManager{TDynamicUrlProvider}"/> class.
    /// </summary>
    /// <param name="dynamicUrlProvider">
    /// The provider used to retrieve the current dynamic base URL.
    /// </param>
    protected BaseDynamicUrlManager(TDynamicUrlProvider dynamicUrlProvider)
    {
        DynamicUrlProvider = dynamicUrlProvider;
    }

    /// <summary>
    /// Attempts to replace the placeholder base address in the specified request URI
    /// with the dynamic base URL supplied by the configured provider.
    /// </summary>
    /// <param name="requestUri">
    /// The original request URI generated by the Refit client.
    /// </param>
    /// <returns>
    /// An <see cref="Option{T}"/> containing the resolved URI when a dynamic base URL is available;
    /// otherwise, <see cref="Option{T}.None"/>.
    /// </returns>
    public Option<Uri> TryGetDynamicUrl(Uri requestUri)
    {
        if (string.IsNullOrWhiteSpace(DynamicUrlProvider.Url))
        {
            return Option<Uri>.None;
        }

        string baseUrl = DynamicUrlProvider.Url;
        string absoluteUri = requestUri.AbsoluteUri;
        int length = "http://dummy.com".Length;
        string relativeUrl = absoluteUri.Substring(length, absoluteUri.Length - length);
        return new Uri(Combine(baseUrl, relativeUrl));
    }

    /// <summary>
    /// Combines a base URL and relative URL while ensuring a single separator
    /// between both segments.
    /// </summary>
    /// <param name="baseUrl">
    /// The base URL.
    /// </param>
    /// <param name="relativeUrl">
    /// The relative URL to append to the base URL.
    /// </param>
    /// <returns>
    /// The combined URL.
    /// </returns>
    private static string Combine(string baseUrl, string relativeUrl)
    {
        return baseUrl.TrimEnd('/') + "/" + relativeUrl.TrimStart('/');
    }
}